#!/usr/bin/env bash
# generate-logrotate.sh — generate a logrotate config for a site's logs.
#
# Usage:
#   ./generate-logrotate.sh --name mysite --path '/var/www/mysite/logs/*.log' \
#       [--rotate 14] [--size 100M] [--compress] [--postrotate 'systemctl reload nginx']
#   ./generate-logrotate.sh --preset wordpress --domain example.com [--write]
#
# Presets: wordpress (wp-content/uploads logs + debug.log), nginx (per-domain
# access/error logs), php-fpm (slow log + error log). --write installs the
# config to /etc/logrotate.d/<name> (needs root); otherwise it prints to stdout.
set -euo pipefail

NAME=""; LOGPATH=""; ROTATE=14; SIZE=""; COMPRESS=1; POSTROTATE=""; WRITE=0; PRESET=""

usage() {
  echo "Usage: $0 --name NAME --path 'GLOB' [--rotate N] [--size 100M] [--no-compress] [--postrotate CMD] [--write]"
  echo "       $0 --preset wordpress|nginx|php-fpm --domain DOMAIN [--write]"
  exit 1
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --name)       NAME="$2"; shift 2 ;;
    --path)       LOGPATH="$2"; shift 2 ;;
    --rotate)     ROTATE="$2"; shift 2 ;;
    --size)       SIZE="$2"; shift 2 ;;
    --compress)   COMPRESS=1; shift ;;
    --no-compress) COMPRESS=0; shift ;;
    --postrotate) POSTROTATE="$2"; shift 2 ;;
    --write)      WRITE=1; shift ;;
    --preset)     PRESET="$2"; shift 2 ;;
    --domain)     DOMAIN="$2"; shift 2 ;;
    -h|--help)    usage ;;
    *) echo "Unknown option: $1" >&2; usage ;;
  esac
done

# Presets fill in name/path/postrotate so a site needs one command.
if [[ -n "$PRESET" ]]; then
  [[ -n "${DOMAIN:-}" ]] || { echo "--domain is required with --preset" >&2; exit 1; }
  NAME="${NAME:-$DOMAIN}"
  case "$PRESET" in
    wordpress)
      LOGPATH="/var/www/$DOMAIN/wp-content/debug.log /var/www/$DOMAIN/logs/*.log"
      ;;
    nginx)
      LOGPATH="/var/log/nginx/$DOMAIN*.log"
      POSTROTATE="${POSTROTATE:-invoke-rc.d nginx rotate >/dev/null 2>&1 || true}"
      ;;
    php-fpm)
      LOGPATH="/var/log/php*.log /var/log/php-fpm/*.log"
      POSTROTATE="${POSTROTATE:-systemctl reload php*-fpm >/dev/null 2>&1 || true}"
      ;;
    *) echo "Unknown preset: $PRESET" >&2; exit 1 ;;
  esac
fi

[[ -n "$NAME" && -n "$LOGPATH" ]] || usage
[[ "$ROTATE" =~ ^[0-9]+$ ]] || { echo "--rotate must be a number" >&2; exit 1; }
[[ "$NAME" =~ ^[A-Za-z0-9_.-]+$ ]] || { echo "--name must be a safe filename" >&2; exit 1; }

{
  echo "# Generated by logrotate-generator — $NAME"
  echo "$LOGPATH {"
  echo "    rotate $ROTATE"
  echo "    daily"
  [[ -n "$SIZE" ]] && echo "    maxsize $SIZE"
  [[ "$COMPRESS" -eq 1 ]] && echo "    compress" || echo "    nocompress"
  echo "    delaycompress"
  echo "    missingok"
  echo "    notifempty"
  echo "    sharedscripts"
  echo "    create 0640 www-data adm"
  if [[ -n "$POSTROTATE" ]]; then
    echo "    postrotate"
    echo "        $POSTROTATE"
    echo "    endscript"
  fi
  echo "}"
} > "/tmp/logrotate-$NAME.conf"

if [[ "$WRITE" -eq 1 ]]; then
  [[ $EUID -eq 0 ]] || { echo "--write needs root (sudo)" >&2; exit 1; }
  cp "/tmp/logrotate-$NAME.conf" "/etc/logrotate.d/$NAME"
  logrotate --debug "/etc/logrotate.d/$NAME" >/dev/null 2>&1 && echo "Installed /etc/logrotate.d/$NAME (config parses OK)" || echo "Installed /etc/logrotate.d/$NAME (logrotate --debug check failed — review it)"
else
  cat "/tmp/logrotate-$NAME.conf"
  echo "# Preview only — rerun with --write (as root) to install to /etc/logrotate.d/$NAME"
fi
